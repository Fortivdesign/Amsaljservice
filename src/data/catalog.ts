/** Räknar fram kontrollsiffran så att EAN-13 blir giltig. */
function ean(base12: string): string {
  const digits = base12.split("").map(Number);
  const sum = digits.reduce((acc, d, i) => acc + d * (i % 2 === 0 ? 1 : 3), 0);
  const check = (10 - (sum % 10)) % 10;
  return base12 + check;
}

