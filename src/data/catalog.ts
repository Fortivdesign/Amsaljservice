// Hjälpfunktioner

export function getProduct(articleOrSlug: string): Product | undefined {
  return products.find((p) => p.slug === articleOrSlug || p.articleNo === articleOrSlug);
}

export function getCategory(slug: string): Category | undefined {
  return categories.find((c) => c.slug === slug);
}

export function getBrand(slug: string): Brand | undefined {
  return brands.find((b) => b.slug === slug);
}

export function productsInCategory(slug: string): Product[] {
  return products.filter((p) => p.category === slug);
}

export function productsByBrand(slug: string): Product[] {
  return products.filter((p) => p.brand === slug);
}

export function packLabel(p: Product): string {
  return `${p.unitsPerCarton} x ${p.unitSize}`;
}

export function currentPrice(p: Product): number {
  return p.offerPrice ?? p.price;
}

export function unitPrice(p: Product): number {
  return currentPrice(p) / p.unitsPerCarton;
}

export function discountPercent(p: Product): number | null {
  if (!p.offerPrice) return null;
  return Math.round((1 - p.offerPrice / p.price) * 100);
}

export function similarProducts(p: Product, count = 4): Product[] {
  const sameCategory = products.filter((x) => x.category === p.category && x.articleNo !== p.articleNo);
  const sameBrand = products.filter((x) => x.brand === p.brand && x.category !== p.category);
  return [...sameCategory.sort((a, b) => b.popularity - a.popularity), ...sameBrand].slice(0, count);
}

export const newProducts = () => products.filter((p) => p.isNew).sort((a, b) => b.addedDate.localeCompare(a.addedDate));
export const topSellers = () => products.filter((p) => p.topSeller).sort((a, b) => b.popularity - a.popularity);
export const offerProducts = () => products.filter((p) => p.offerPrice);
